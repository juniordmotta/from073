
-- Table for storing push notification subscriptions
CREATE TABLE public.push_subscriptions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  endpoint text NOT NULL,
  p256dh text NOT NULL,
  auth_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id, endpoint)
);

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

-- Users can manage their own subscriptions
CREATE POLICY "Users can view their own subscriptions"
ON public.push_subscriptions FOR SELECT
USING (auth.uid() = user_id);

CREATE POLICY "Users can create their own subscriptions"
ON public.push_subscriptions FOR INSERT
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete their own subscriptions"
ON public.push_subscriptions FOR DELETE
USING (auth.uid() = user_id);

-- Table to store VAPID keys (generated by edge function)
CREATE TABLE public.push_config (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  key_name text UNIQUE NOT NULL,
  key_value text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.push_config ENABLE ROW LEVEL SECURITY;

-- Only public key readable by authenticated users
CREATE POLICY "Authenticated users can read public VAPID key"
ON public.push_config FOR SELECT
USING (key_name = 'vapid_public_key' AND auth.uid() IS NOT NULL);

-- Table to track sent push notifications (avoid duplicates)
CREATE TABLE public.push_sent_log (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  arbitrage_id uuid NOT NULL REFERENCES public.arbitrages(id) ON DELETE CASCADE,
  user_id uuid NOT NULL,
  sent_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(arbitrage_id, user_id)
);

ALTER TABLE public.push_sent_log ENABLE ROW LEVEL SECURITY;

-- No client access - only edge function via service role
CREATE POLICY "No client access to push_sent_log"
ON public.push_sent_log FOR SELECT
USING (false);

-- Enable pg_cron and pg_net for scheduled push notifications
CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA pg_catalog;
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;
